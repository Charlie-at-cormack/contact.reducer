// Migration verification scan for one domain.
// A matching IP alone is never treated as proof: "verified" needs DNS on the VPS,
// healthy HTTP(S) and the verification marker served (or a confirmed redirect).
import {
  makeResolver, resolveHost, dnsQuery, makeLookup, fetchChain, chainSummary, request,
  ipMatches, cdnForIp, cdnFromHeaders, platformFromHeaders, isIonosMx, isIonosNs,
} from './net.js';
import { providerOf } from '../public/health.js';

// Reverse DNS names the host behind an unrecognised IP (e.g. Wix, AWS, another IONOS server).
const ptrCache = new Map();
async function ptrOf(resolver, ip) {
  const c = ptrCache.get(ip);
  if (c && Date.now() - c.t < 3600e3) return c.v;
  const r = await dnsQuery(resolver, 'reverse', ip);
  const v = r.ok && r.v.length ? String(r.v[0]).replace(/\.$/, '') : '';
  ptrCache.set(ip, { v, t: Date.now() });
  return v;
}

function classifier(settings, d) {
  const exportIps = [...(d.exportIps?.v4 || []), ...(d.exportIps?.v6 || [])];
  return (ip, family) => {
    for (const v of settings.vps || []) {
      const list = family === 4 ? v.ipv4 : v.ipv6;
      if ((list || []).some(rule => ipMatches(ip, rule))) return { ip, family, cls: 'vps', vps: v.id, label: v.name };
    }
    if ((settings.oldRanges || []).some(rule => ipMatches(ip, rule))) return { ip, family, cls: 'old', label: 'Old hosting (IONOS range)' };
    const cdn = cdnForIp(ip);
    if (cdn) return { ip, family, cls: 'cdn', label: `${cdn} proxy` };
    const inExport = exportIps.some(x => ipMatches(ip, x));
    return { ip, family, cls: 'other', label: inExport ? 'Unrecognised (same as IONOS export)' : 'Unrecognised' };
  };
}

// Error text that names the hop that failed when it was not the first one.
function failDetail(c) {
  const last = c.hops[c.hops.length - 1];
  if (c.hops.length < 2 || !last) return c.error;
  return `${c.error} at ${last.url} (after ${c.hops.slice(0, -1).map(x => x.status).join(' → ')})`;
}

const hostOf = u => { try { return new URL(u).hostname.toLowerCase(); } catch { return ''; } };
const bare = h => String(h || '').toLowerCase().replace(/^www\./, '');

// A 200 response that is really a placeholder: no website has been set up yet.
function placeholderOf(chain) {
  const f = chain?.final;
  if (!f?.status || f.status >= 400) return null;
  const html = String(f.body || '');
  const title = (html.match(/<title[^>]*>([^<]*)/i)?.[1] || '').trim();
  if (/login_up\.php/i.test(chain.finalUrl || '') || /^Plesk( Obsidian| Onyx)?\b/i.test(title)) return 'Plesk login page';
  if (/Domain Default page/i.test(title) || /plesk-default-page|This page is generated by Plesk/i.test(html)) return 'Plesk default page';
  if (/This domain (name )?(has just been|was recently|is) registered|domain is parked|parkingcrew|sedoparking|bodis\.com/i.test(html) && html.length < 60000) return 'Parking page';
  if (/^(It works!|Welcome to nginx!|Apache2 (Ubuntu|Debian) Default Page|Test Page for the (Apache|nginx))/i.test(title)) return 'Web server default page';
  if (/defaultwebpage\.cgi/i.test(html) || /^cPanel/i.test(title)) return 'Hosting default page';
  return null;
}

async function zoneNs(resolver, name) {
  const labels = name.split('.');
  for (let i = 0; i < Math.min(4, labels.length - 1); i++) {
    const zone = labels.slice(i).join('.');
    const r = await dnsQuery(resolver, 'resolveNs', zone);
    if (r.ok && r.v.length) return { zone, ns: r.v };
  }
  return { zone: null, ns: [] };
}

async function markerPublic(host, path, tokens, o) {
  const allow = o.allowHosts;
  let c = await fetchChain(`https://${host}${path}`, { ...o, maxHops: 3, maxBody: 4096, allowHosts: allow });
  let scheme = 'https';
  if (c.error && !c.final?.status) {
    c = await fetchChain(`http://${host}${path}`, { ...o, maxHops: 3, maxBody: 4096, allowHosts: allow });
    scheme = 'http';
  }
  const status = c.final?.status || null;
  const body = String(c.final?.body || '');
  const hit = status === 200 ? tokens.find(t => body.includes(t.token)) : null;
  return {
    host, scheme, url: c.finalUrl, status, error: c.error || null,
    matched: hit ? hit.id : null,
    matchedName: hit ? hit.name : null,
    wrong: status === 200 && !hit && /migration-check:/.test(body),
    snippet: status === 200 && !hit ? body.replace(/\s+/g, ' ').slice(0, 80) : '',
  };
}

async function markerDirect(v, ip, root, path, tokens, timeout) {
  const t = tokens.find(x => x.id === v.id);
  const attempt = async scheme => {
    let url = `${scheme}://${root}${path}`;
    for (let i = 0; i < 3; i++) {
      const r = await request(url, { connectIp: ip, maxBody: 4096, timeout });
      if (r.error) return { error: r.error };
      if ([301, 302, 307, 308].includes(r.status) && r.headers.location) {
        let next;
        try { next = new URL(r.headers.location, url); } catch { return { status: r.status }; }
        if (bare(next.hostname) !== bare(root)) return { status: r.status, note: `redirects to ${next.hostname}` };
        url = next.href;
        continue;
      }
      return { status: r.status, body: String(r.body || '') };
    }
    return { status: 0, error: 'Too many redirects' };
  };
  let r = await attempt('https');
  if (r.error) r = await attempt('http');
  let result = 'notfound';
  if (r.error) result = 'error';
  else if (r.status === 200 && t && r.body.includes(t.token)) result = 'found';
  else if (r.status === 200 && /migration-check:/.test(r.body || '')) result = 'wrong';
  return { vps: v.id, name: v.name, ip, result, status: r.status || null, detail: r.error || r.note || '' };
}

export async function verifyDomain(d, settings) {
  const t0 = Date.now();
  const timeout = settings.timeoutMs || 10000;
  const root = String(d.domain).toLowerCase().replace(/\.$/, '');
  const resolver = makeResolver(settings);
  const classify = classifier(settings, d);
  const checks = [];
  const add = (level, label, detail = '') => checks.push({ level, label, detail });

  const hostList = [{ role: 'root', host: root }];
  if (!root.startsWith('www.')) hostList.push({ role: 'www', host: `www.${root}` });

  // ---- DNS ----
  const hosts = await Promise.all(hostList.map(async h => {
    const r = await resolveHost(resolver, h.host);
    return { ...h, ...r, ips: [...r.a.map(ip => classify(ip, 4)), ...r.aaaa.map(ip => classify(ip, 6))] };
  }));
  const [mxR, nsR] = await Promise.all([dnsQuery(resolver, 'resolveMx', root), zoneNs(resolver, root),
    ...hosts.flatMap(h => h.ips.filter(i => i.cls === 'other').map(async i => {
      i.ptr = await ptrOf(resolver, i.ip);
      i.provider = providerOf(i.ip, i.ptr);
      if (i.provider) i.label = `${i.provider} (not a configured VPS)`;
    }))]);
  const mx = mxR.ok ? mxR.v.sort((a, b) => a.priority - b.priority).map(m => ({ host: m.exchange, priority: m.priority, ionos: isIonosMx(m.exchange) })) : [];

  // ---- HTTP ----
  const lookupMap = {};
  for (const h of hosts) lookupMap[h.host] = [...h.a, ...h.aaaa];
  const lookup = makeLookup(lookupMap);
  await Promise.all(hosts.map(async h => {
    h.http = {};
    if (!h.ips.length) return;
    const [plain, secure] = await Promise.all([
      fetchChain(`http://${h.host}/`, { lookup, timeout, maxBody: 200000 }),
      fetchChain(`https://${h.host}/`, { lookup, timeout, maxBody: 200000 }),
    ]);
    h.http.http = chainSummary(plain);
    h.http.https = chainSummary(secure);
    h.http.placeholder = placeholderOf(secure.final?.status ? secure : plain);
    h._finalHeaders = secure.final?.headers || plain.final?.headers || {};
    h._secure = secure;
    h._plain = plain;
  }));

  // ---- CDN / proxy ----
  let cdn = null;
  for (const h of hosts) {
    for (const ip of h.ips) if (ip.cls === 'cdn') cdn = cdn || ip.label.replace(/ proxy$/, '');
    const hc = cdnFromHeaders(h._finalHeaders || {});
    if (hc) cdn = cdn || hc;
  }
  const platform = hosts.map(h => platformFromHeaders(h._finalHeaders || {})).find(Boolean) || null;

  // ---- Marker ----
  const tokens = (settings.vps || []).filter(v => String(v.token || '').trim()).map(v => ({ id: v.id, name: v.name, token: String(v.token).trim() }));
  const markerPath = String(settings.markerPath || '').trim();
  const markerOn = !!(markerPath && markerPath.startsWith('/') && tokens.length);
  const allowHosts = hosts.map(h => h.host);
  if (markerOn) {
    await Promise.all(hosts.map(async h => {
      if (!h.ips.length) return;
      h.marker = await markerPublic(h.host, markerPath, tokens, { lookup, timeout, allowHosts });
    }));
  }
  const direct = [];
  if (markerOn) {
    await Promise.all((settings.vps || []).map(async v => {
      const ip = (v.ipv4 || []).find(x => x && !x.includes('/'));
      if (!ip) return;
      direct.push(await markerDirect(v, ip, root, markerPath, tokens, timeout));
    }));
  }

  // ---- Evaluate ----
  const rootH = hosts[0];
  let old = false, other = false, allVps = true, anyIp = false, httpFail = false;
  const vpsIds = new Set();
  for (const h of hosts) {
    const label = h.role === 'root' ? root : h.host;
    if (!h.ips.length) {
      if (h.role === 'root') add('fail', `${label}: no DNS address`, h.error || '');
      else add('warn', `${label}: no DNS address`, `${h.error || ''}. Check whether www should exist.`);
      continue;
    }
    anyIp = true;
    if (h.cname.length) add('info', `${label}: CNAME`, h.cname.join(', '));
    for (const ip of h.ips) {
      const rec = ip.family === 4 ? 'A' : 'AAAA';
      if (ip.cls === 'vps') { vpsIds.add(ip.vps); add('pass', `${label} ${rec} ${ip.ip}`, ip.label); continue; }
      allVps = false;
      if (ip.cls === 'old') { old = true; add('fail', `${label} ${rec} ${ip.ip}`, `${ip.label}${ip.family === 6 ? ': IPv6 visitors still reach old hosting' : ''}`); }
      else if (ip.cls === 'cdn') add('review', `${label} ${rec} ${ip.ip}`, ip.label);
      else { other = true; add('review', `${label} ${rec} ${ip.ip}`, ip.label); }
    }
    const vpsHasV6 = (settings.vps || []).some(v => (v.ipv6 || []).length && h.ips.some(ip => ip.vps === v.id));
    if (vpsHasV6 && !h.aaaa.length) add('info', `${label}: no AAAA record`, 'The VPS has IPv6 configured but this name has no AAAA record.');

    // HTTPS
    const s = h._secure;
    const firstTls = s?.hops?.[0]?.tls;
    if (s?.error && !s.final?.status) { httpFail = true; add('fail', `https://${h.host}/ failed`, failDetail(s)); }
    else if (s) {
      const fs = s.final?.status;
      const chain = s.hops.map(x => x.status || 'ERR').join(' → ');
      if (firstTls && !firstTls.authorized) { httpFail = true; add('fail', `https://${h.host}/ certificate invalid`, `${firstTls.error || 'untrusted'}${firstTls.cert ? ` (CN ${firstTls.cert.subject}, ${firstTls.cert.issuer})` : ''}`); }
      else if (firstTls?.cert) add('pass', `https://${h.host}/ certificate valid`, `${firstTls.cert.issuer || ''}, expires ${firstTls.cert.validTo}`);
      if (s.error) { httpFail = true; add('fail', `https://${h.host}/ ${s.error}`, chain); }
      else if (fs >= 200 && fs < 300) add('pass', `https://${h.host}/ → ${fs}`, `${chain}${s.finalUrl !== `https://${h.host}/` ? ` · ends at ${s.finalUrl}` : ''}`);
      else { httpFail = true; add('fail', `https://${h.host}/ → ${fs}`, `${chain} · ends at ${s.finalUrl}`); }
    }
    // HTTP
    const p = h._plain;
    if (p?.error && !p.final?.status) add('warn', `http://${h.host}/ failed`, failDetail(p));
    else if (p) {
      const first = p.hops[0];
      if (first?.status >= 200 && first.status < 300) add('warn', `http://${h.host}/ does not redirect to HTTPS`, `Served ${first.status} over plain HTTP`);
      else if (p.final?.status >= 400) add('warn', `http://${h.host}/ → ${p.final.status}`, p.hops.map(x => x.status).join(' → '));
      else add('pass', `http://${h.host}/ → ${p.hops.map(x => x.status).join(' → ')}`, `ends at ${p.finalUrl}`);
    }
  }

  // Redirect / canonical analysis
  const finalHost = hostOf(rootH._secure?.finalUrl || rootH._plain?.finalUrl || '');
  const offsite = finalHost && bare(finalHost) !== bare(root) ? finalHost : null;
  const expected = d.redirectTarget ? hostOf(/^https?:/i.test(d.redirectTarget) ? d.redirectTarget : `http://${d.redirectTarget}`) : null;
  let redirectOk = false;
  if (offsite) {
    const finalStatus = rootH._secure?.final?.status || rootH._plain?.final?.status;
    if (expected && bare(expected) === bare(offsite) && finalStatus && finalStatus < 400) { redirectOk = true; add('pass', `Redirects to ${offsite}`, 'Matches the redirect target in the IONOS export'); }
    else add('review', `Redirects to ${offsite}`, expected ? `IONOS export target was ${expected}` : 'Confirm this redirect is intended');
  }
  const wwwH = hosts.find(h => h.role === 'www');
  if (wwwH?.ips.length && rootH.ips.length && !offsite) {
    const a = rootH._secure?.finalUrl, b = wwwH._secure?.finalUrl;
    if (a && b && a !== b) add('warn', 'Root and www end at different URLs', `${a} vs ${b}`);
  }

  // Marker results
  const markerHosts = hosts.filter(h => h.ips.length && h.marker);
  let markerMatched = false, markerWrong = false;
  if (!markerOn) add('review', 'No verification marker configured', 'Set a marker path and VPS tokens in Settings. An IP match alone is not proof of migration.');
  else if (!offsite) {
    const ok = markerHosts.filter(h => h.marker.matched);
    markerMatched = markerHosts.length > 0 && ok.length === markerHosts.length;
    for (const h of markerHosts) {
      const m = h.marker;
      if (m.matched) {
        const mismatch = h.ips.some(ip => ip.cls === 'vps') && !h.ips.some(ip => ip.vps === m.matched);
        if (mismatch) { markerWrong = true; add('review', `Marker on ${h.host} belongs to ${m.matchedName}`, 'DNS points to a different VPS than the one serving the marker'); }
        else add('pass', `Marker served on ${h.host}`, `${m.matchedName} token matched (${m.scheme})`);
      } else if (m.wrong) { markerWrong = true; add('review', `Marker on ${h.host} has an unknown token`, m.snippet); }
      else add('review', `Marker not found on ${h.host}`, `${m.status ? `HTTP ${m.status}` : m.error || 'no response'} at ${m.url}`);
    }
  }
  for (const r of direct) {
    if (r.result === 'found') add('info', `Site answers on ${r.name} (direct)`, `Marker found when requesting ${root} from ${r.ip}`);
    else if (r.result === 'wrong') add('info', `${r.name} (direct): unexpected token`, '');
  }

  const mxIonos = mx.some(m => m.ionos);
  if (mx.length) add('info', `MX: ${mx.map(m => m.host).join(', ')}`, mxIonos ? 'Email still handled by IONOS' : '');
  const nsIonos = nsR.ns.some(isIonosNs);
  if (nsR.ns.length) add('info', `Nameservers (${nsR.zone}): ${nsR.ns.slice(0, 4).join(', ')}`, nsIonos ? 'DNS zone hosted at IONOS' : '');
  if (cdn) add('review', `Behind ${cdn}`, 'Proxy/CDN hides the origin server');
  if (platform) add('info', `Platform headers: ${platform}`, '');

  // ---- Verdict ----
  let verdict, summary;
  const vpsNames = [...vpsIds].map(id => (settings.vps || []).find(v => v.id === id)?.name || id).join(', ');
  if (!anyIp) { verdict = 'failed'; summary = `No DNS address for ${root}${rootH.error ? ` (${rootH.error})` : ''}`; }
  else if (old) {
    verdict = 'old';
    const oldRecs = hosts.flatMap(h => h.ips.filter(i => i.cls === 'old').map(i => `${h.role === 'root' ? '' : 'www '}${i.family === 6 ? 'AAAA' : 'A'} ${i.ip}`));
    summary = `${vpsIds.size ? 'Partly on old hosting' : 'Still on old hosting'}: ${oldRecs.join(', ')}`;
  } else if (!rootH.ips.length) { verdict = 'failed'; summary = `Root ${root} has no DNS address`; }
  else if (allVps) {
    if (httpFail) { verdict = 'failed'; summary = `DNS on ${vpsNames}, but HTTP(S) checks fail`; }
    else if (offsite) {
      if (redirectOk) { verdict = 'verified'; summary = `Redirect served from ${vpsNames} to ${offsite} (matches IONOS target)`; }
      else { verdict = 'review'; summary = `DNS on ${vpsNames}; redirects to ${offsite}. Confirm the target.`; }
    } else if (!markerOn) { verdict = 'review'; summary = `DNS on ${vpsNames} and HTTP OK; no marker configured, so not proven`; }
    else if (markerMatched && !markerWrong) { verdict = 'verified'; summary = `On ${vpsNames}, HTTPS OK, marker matched`; }
    else if (markerWrong) { verdict = 'review'; summary = 'Marker token does not match the VPS that DNS points to'; }
    else { verdict = 'review'; summary = `DNS on ${vpsNames} and HTTP OK, but the marker was not found`; }
  } else if (cdn && !other) {
    if (markerMatched && !httpFail) { verdict = 'verified'; summary = `Behind ${cdn}; origin confirmed by marker`; }
    else { verdict = 'review'; summary = `Behind ${cdn}: origin cannot be confirmed${markerOn ? ' (marker not found)' : ''}`; }
  } else {
    verdict = 'review';
    const ips = hosts.flatMap(h => h.ips.filter(i => i.cls === 'other').map(i => i.ip));
    summary = `Points to unrecognised address${ips.length > 1 ? 'es' : ''}: ${[...new Set(ips)].join(', ')}`;
  }

  return {
    at: new Date().toISOString(),
    ms: Date.now() - t0,
    verdict,
    summary,
    flags: { cdn, platform, offsite, redirectOk, mxIonos, nsIonos, markerOn, markerMatched },
    hosts: hosts.map(h => ({
      role: h.role, host: h.host, a: h.a, aaaa: h.aaaa, cname: h.cname, error: h.error, ips: h.ips,
      http: h.http, marker: h.marker || null,
    })),
    direct,
    mx,
    ns: nsR.ns,
    zone: nsR.zone,
    checks,
  };
}
